// Generates `src/lib/icons.generated.ts` from the source SVGs in `icons/`.
//
// The `icons/` directory is the single source of truth for the icon library.
// This script discovers every `*.svg`, derives a display label from the SVG's
// `<text>` element (falling back to the capitalized filename), and emits a
// TypeScript module consumed by `src/lib/icons.ts`. Adding a new SVG requires
// no other manual edits — the UI, `icons.json`, and `llms.txt` all pick it up.
//
// Run with: node scripts/generate-icon-manifest.mjs

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const iconsDir = join(root, 'icons');
const outFile = join(root, 'src', 'lib', 'icons.generated.ts');

// Matches the first `<text ...>content</text>` element (wordmark variants).
const TEXT_RE = /<text\b[^>]*>([^<]+)<\/text>/;

/** Capitalizes a filename stem, e.g. `clean` -> `Clean`. */
function capitalize(name) {
    return name.charAt(0).toUpperCase() + name.slice(1);
}

/** Derives a display label from an SVG's `<text>` content, or the filename. */
function deriveLabel(filename, svg) {
    const match = svg.match(TEXT_RE);
    if (match && match[1].trim()) {
        return match[1].trim();
    }
    return capitalize(filename);
}

const variants = readdirSync(iconsDir)
    .filter(f => f.endsWith('.svg'))
    .map(f => f.replace(/\.svg$/, ''))
    .sort();

const entries = variants.map(variant => {
    const svg = readFileSync(join(iconsDir, `${variant}.svg`), 'utf8');
    const label = deriveLabel(variant, svg);
    return { id: variant, label };
});

const header = `// AUTO-GENERATED by scripts/generate-icon-manifest.mjs — do not edit by hand.
// Source of truth: the \`icons/*.svg\` files. Re-run the script to regenerate.

export interface GeneratedIconVariant {
    id: string;
    label: string;
}

export const GENERATED_ICON_VARIANTS: GeneratedIconVariant[] = ${JSON.stringify(
    entries,
    null,
    4
)};
`;

writeFileSync(outFile, header);
console.log(
    `Wrote ${outFile} (${entries.length} variants: ${variants.join(', ')})`
);
